async function main() {
  console.log('📚 بدء إضافة 10 مراحل ثقافية علمية...\n');

  let chapter = await prisma.chapter.findFirst({ where: { title: 'البدايات' } });
  if (!chapter) {
    chapter = await prisma.chapter.create({
      data: {
        title: 'محاضرات ثقافية',
        description: 'مراحل ثقافية علمية مستوحاة من محاضرات السيد عبدالملك بدرالدين الحوثي',
        icon: '📚', color: 'oklch(0.78 0.13 80)', order: 1, unlockAt: 0, isPublished: true,
      }
    });
    console.log(`✅ فصل جديد: ${chapter.title} (#${chapter.id})`);
  } else {
    console.log(`📋 فصل موجود: ${chapter.title} (#${chapter.id})`);
  }

  const chapterId = chapter.id;
  const lastLevel = await prisma.level.findFirst({ where: { chapterId }, orderBy: { number: 'desc' } });
  let nextNumber = (lastLevel?.number || 0) + 1;

  for (const lvl of levels) {
    console.log(`📦 ${lvl.title} (${lvl.difficulty}) - #${nextNumber}`);
    const allLetters = lvl.words.flatMap(w => w.text.split(''));
    const uniqueLetters = [...new Set(allLetters)];

    const level = await prisma.level.create({
      data: {
        chapterId, number: nextNumber, title: lvl.title,
        difficulty: lvl.difficulty, gameMode: 'crossword', puzzleType: 'text',
        timeLimit: 0, gridSizeRows: 10, gridSizeCols: 10,
        availableLetters: uniqueLetters.join(','),
        bonusWords: '', reward: 100, hintCost: 10,
        status: 'published', isPublished: true,
        learningGoals: JSON.stringify(lvl.description ? [lvl.description] : []),
      }
    });

    let wordNumber = 1;
    let currentRow = 0;
    let currentCol = 0;

    for (const w of lvl.words) {
      const direction = wordNumber % 2 === 0 ? 'down' : 'across';
      await prisma.word.create({
        data: {
          levelId: level.id, text: w.text, clue: w.clue,
          category: 'معرفة ثقافية', direction,
          startRow: currentRow, startCol: currentCol, number: wordNumber,
        }
      });
      for (let i = 0; i < w.text.length; i++) {
        const row = direction === 'down' ? currentRow + i : currentRow;
        const col = direction === 'across' ? currentCol + i : currentCol;
        await prisma.cell.create({
          data: { levelId: level.id, row, col, letter: w.text[i], number: i === 0 ? wordNumber : null }
        });
      }
      if (direction === 'down') { currentCol += 2; } else { currentRow += 2; }
      wordNumber++;
    }
    console.log(`   ✅ ${lvl.words.length} كلمة + ${lvl.words.length * 3} خلايا`);
    nextNumber++;
  }

  console.log(`\n🎉 تم! ${levels.length} مراحل، ${levels.length * 10} سؤال ثقافي`);
  console.log(`   الفصل: ${chapter.title} (#${chapterId})`);
  await prisma.$disconnect();
}
main().catch(e => { console.error('❌', e); process.exit(1); });
