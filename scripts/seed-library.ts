async function seedLibrary() {
  console.log("📚 بدء زرع بيانات المكتبة...\n");

  // 1. زرع التصنيفات
  console.log("📂 زرع التصنيفات...");
  const categoryMap = new Map<string, number>();

  for (const cat of categories) {
    const created = await db.bookCategory.upsert({
      where: { slug: cat.slug },
      create: cat,
      update: cat,
    });
    categoryMap.set(cat.slug, created.id);
    console.log(`  ✅ ${cat.icon} ${cat.name} (ID: ${created.id})`);
  }

  // 2. زرع الكتب
  console.log("\n📖 زرع الكتب...");
  for (const book of books) {
    const categoryId = categoryMap.get(book.categorySlug);
    if (!categoryId) {
      console.warn(`  ⚠️ التصنيف غير موجود: ${book.categorySlug}`);
      continue;
    }

    // التحقق من وجود الكتاب (بالعنوان)
    const existing = await db.book.findFirst({
      where: { title: book.title },
      select: { id: true },
    });

    if (existing) {
      console.log(`  ⏭️  "${book.title}" — موجود بالفعل`);
      continue;
    }

    const createdBook = await db.book.create({
      data: {
        categoryId,
        title: book.title,
        author: book.author,
        description: book.description,
        contentType: "text",
        difficulty: book.difficulty,
        readingTimeMin: book.readingTimeMin,
        pages: book.pages,
        language: "ar",
        keywords: JSON.stringify(book.keywords),
        isFeatured: book.isFeatured || false,
        isPublished: true,
      },
    });

    console.log(`  ✅ 📕 "${book.title}" — ${book.author} (ID: ${createdBook.id})`);

    // زرع الفصول
    for (let i = 0; i < book.chapters.length; i++) {
      const ch = book.chapters[i];
      await db.bookChapter.create({
        data: {
          bookId: createdBook.id,
          number: i + 1,
          title: ch.title,
          content: ch.content,
          readingTimeMin: ch.readingTimeMin,
          isFree: true,
          isPublished: true,
        },
      });
      console.log(`     📑 فصل ${i + 1}: ${ch.title} (${ch.readingTimeMin} دقيقة)`);
    }
  }

  // 3. الإحصائيات
  const totalCategories = await db.bookCategory.count();
  const totalBooks = await db.book.count();
  const totalChapters = await db.bookChapter.count();
  const publishedBooks = await db.book.count({ where: { isPublished: true } });
  const featuredBooks = await db.book.count({ where: { isFeatured: true } });

  console.log("\n" + "=".repeat(60));
  console.log("✅ اكتمل زرع بيانات المكتبة بنجاح!");
  console.log("=".repeat(60));
  console.log(`📂 التصنيفات: ${totalCategories}`);
  console.log(`📚 الكتب: ${totalBooks} (${publishedBooks} منشورة)`);
  console.log(`⭐ كتب مميزة: ${featuredBooks}`);
  console.log(`📑 الفصول: ${totalChapters}`);
  console.log("=".repeat(60));
}

seedLibrary()
  .catch((e) => {
    console.error("❌ خطأ في الزرع:", e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
