async function apiFetch(path, options = {}) {
  const url = `${API_BASE}${path}`;
  const res = await fetch(url, {
    ...options,
    headers: { 'Content-Type': 'application/json', ...(options.headers || {}) },
  });
  const data = await res.json();
  if (!res.ok) throw new Error(data.error || data.details?.join('; ') || `HTTP ${res.status}`);
  return data;
}

function buildWordsAndCells(words) {
  const apiWords = [];
  const apiCells = [];
  let wordNumber = 1;
  let currentRow = 0;
  let currentCol = 0;

  for (const w of words) {
    const direction = wordNumber % 2 === 0 ? 'down' : 'across';
    apiWords.push({
      text: w.text,
      clue: w.clue,
      category: 'معرفة ثقافية',
      direction,
      startRow: currentRow,
      startCol: currentCol,
      number: wordNumber,
    });

    for (let i = 0; i < w.text.length; i++) {
      const row = direction === 'down' ? currentRow + i : currentRow;
      const col = direction === 'across' ? currentCol + i : currentCol;
      apiCells.push({ row, col, letter: w.text[i], number: i === 0 ? wordNumber : null });
    }

    if (direction === 'down') { currentCol += 1; } else { currentRow += 1; }
    wordNumber++;
  }
  return { apiWords, apiCells };
}

